// Writes supabase/story-catalog.sql from the mission files: the server's own copy of every mission's id,
// chapter, route and reward, so it can check what players record. Run: npx vitest run scripts/story-sql.test.ts
import { it } from "vitest";
import { writeFileSync } from "node:fs";
import { STORY } from "../src/data/story";

it("writes the story catalogue SQL", () => {
  const q = (s: string | undefined) => (s ? `'${s.replace(/'/g, "''")}'` : "null");
  const rows = STORY.map(m => `  (${q(m.id)}, ${m.ch}, ${q(m.route)}, ${m.side ? "true" : "false"}, ${m.reward.money ?? 0}, ${m.reward.xp ?? 0})`);
  writeFileSync("supabase/story-catalog.sql", `-- Generated by scripts/story-sql.test.ts from src/data/story. Do not edit by hand.
-- Run in Supabase → SQL Editor after update-2026-11-story.sql (and again whenever missions change).
insert into public.story_catalog (id, chapter, route, side, reward_naira, reward_xp) values
${rows.join(",\n")}
on conflict (id) do update set chapter = excluded.chapter, route = excluded.route, side = excluded.side,
  reward_naira = excluded.reward_naira, reward_xp = excluded.reward_xp;
`);
});
